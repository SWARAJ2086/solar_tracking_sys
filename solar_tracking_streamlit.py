def predict_solar(day, hour, temp, humidity, cloud, wind):
    el, az = sun_position(day, hour)
    if el <= 2:
        return "Night / Sun Below Horizon: Park Panel", "-", "0.00 kW"
    row = pd.DataFrame([{
        "hour": hour, "day_of_year": day, "temperature": temp, "humidity": humidity,
        "cloud_cover": cloud, "wind_speed": wind, "sun_elevation": float(el), "sun_azimuth": float(az)
    }])[bundle["features"]]
    power = bundle["power"].predict(row)[0]
    track = bundle["mode"].predict(row)[0]
    if track == 1:
        return "TRACK THE SUN", f"Azimuth: {az:.0f}°, Tilt: {90 - el:.0f}°", f"{power:.2f} kW"
    return "KEEP FLAT / STOWED (Cloudy or High Wind)", "Tilt: 0° (Flat)", f"{power:.2f} kW"


