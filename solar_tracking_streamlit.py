# Calculate Sun Elevation & Azimuth (Latitude 18.5° N)
def sun_position(day_of_year, hour, lat=18.5):
    decl = np.radians(23.45 * np.sin(np.radians(360 / 365 * (284 + day_of_year))))
    w = np.radians(15 * (hour - 12))
    phi = np.radians(lat)
    sin_el = np.sin(phi) * np.sin(decl) + np.cos(phi) * np.cos(decl) * np.cos(w)
    el = np.degrees(np.arcsin(np.clip(sin_el, -1, 1)))
    cos_az = (np.sin(decl) - np.sin(np.radians(el)) * np.sin(phi)) / (np.cos(np.radians(el)) * np.cos(phi) + 1e-9)
    az = np.degrees(np.arccos(np.clip(cos_az, -1, 1)))
    az = np.where(w > 0, 360 - az, az)
    return el, az

# Generate 1-Year Hourly Daylight Dataset
rng = np.random.default_rng(42)
days, hours = np.meshgrid(np.arange(1, 366), np.arange(6, 19), indexing="ij")
day, hour = days.ravel(), hours.ravel()
month = (pd.to_datetime("2025-01-01") + pd.to_timedelta(day - 1, unit="D")).month.to_numpy()

month_cloud = np.array([10, 10, 15, 18, 28, 70, 82, 80, 68, 35, 15, 10])
cloud = np.clip(month_cloud[month - 1] + rng.normal(0, 18, 365)[day - 1] + rng.normal(0, 10, day.size), 0, 100)
temp = 24 + 5 * np.sin(2 * np.pi * (day - 44) / 365) + 7 * np.sin(np.pi * (hour - 8) / 12) - 0.05 * cloud + rng.normal(0, 1, day.size)
humidity = np.clip(30 + 0.6 * cloud - 0.8 * (temp - 25) + rng.normal(0, 5, day.size), 15, 100)
wind = rng.gamma(3, 1.4, day.size) + 3 * np.isin(month, [6, 7, 8, 9])

el, az = sun_position(day, hour)
keep = el > 2
day, hour, cloud, temp, humidity, wind, el, az = [a[keep] for a in (day, hour, cloud, temp, humidity, wind, el, az)]

sin_el = np.sin(np.radians(el))
ghi = np.clip(1000 * (sin_el ** 1.15) * (1 - 0.75 * (cloud / 100) ** 3.4), 0, None)
direct_share = 0.88 * (1 - cloud / 100) ** 1.3
dni = np.clip(ghi * direct_share / sin_el, 0, 950)
diffuse = ghi * (1 - direct_share)

beta = np.radians(18.5)
cos_inc = np.clip(sin_el * np.cos(beta) + np.cos(np.radians(el)) * np.sin(beta) * np.cos(np.radians(az - 180)), 0, 1)

def calc_power(poa):
    t_cell = temp + 0.03 * poa
    return np.clip(5 * (poa / 1000) * (1 - 0.004 * (t_cell - 25)) * 0.9 * (1 + rng.normal(0, 0.02, poa.size)), 0, None)

power_tracker = calc_power(dni + diffuse)
power_fixed = calc_power(dni * cos_inc + diffuse * (1 + np.cos(beta)) / 2)
track_needed = ((cloud < 70) & (el >= 15) & (wind < 12)).astype(int)

df = pd.DataFrame({
    "day_of_year": day, "hour": hour, "temperature": temp, "humidity": humidity,
    "cloud_cover": cloud, "wind_speed": wind, "sun_elevation": el, "sun_azimuth": az,
    "power_kw": power_tracker, "fixed_power_kw": power_fixed, "track_needed": track_needed
}).round(2)

# Clean missing values & outliers
df["humidity"] = df["humidity"].fillna(df["humidity"].median())
df.to_csv("solar_tracking_dataset.csv", index=False)
print(f"Dataset ready: {df.shape[0]} rows | Tracker gives {(df['power_kw'].sum()/df['fixed_power_kw'].sum()-1)*100:.1f}% more energy!")

