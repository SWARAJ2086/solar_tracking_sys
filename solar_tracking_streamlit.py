# 1. Power Prediction (Regression)
lr = LinearRegression().fit(X_train, yp_train)
rf_reg = RandomForestRegressor(n_estimators=100, random_state=42).fit(X_train, yp_train)

print("--- Power Prediction (kW) ---")
