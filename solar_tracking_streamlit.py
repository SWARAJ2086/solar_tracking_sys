print(f"Random Forest     | R2: {r2_score(yp_test, rf_reg.predict(X_test)):.3f} | MAE: {mean_absolute_error(yp_test, rf_reg.predict(X_test)):.3f} kW")

# 2. Tracking Decision (Classification)
log_reg = Pipeline([("scale", StandardScaler()), ("m", LogisticRegression())]).fit(X_train, yt_train)
rf_clf = RandomForestClassifier(n_estimators=100, random_state=42).fit(X_train, yt_train)

print("\n--- Tracking Mode Decision ---")
print(f"Logistic Regression | Accuracy: {accuracy_score(yt_test, log_reg.predict(X_test)):.3f} | F1: {f1_score(yt_test, log_reg.predict(X_test)):.3f}")
print(f"Random Forest       | Accuracy: {accuracy_score(yt_test, rf_clf.predict(X_test)):.3f} | F1: {f1_score(yt_test, rf_clf.predict(X_test)):.3f}")

